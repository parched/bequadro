using Bequadro.Generator.Common;

namespace Bequadro.Generator.Emit;

/// <summary>
/// Produces the C# source of the schema set's fingerprint (SER-015).
/// </summary>
internal static class FingerprintEmitter
{
    /// <summary>
    /// The class that holds the fingerprint, in the global namespace. Renaming keeps schema names from taking it
    /// (API-002).
    /// </summary>
    public const string ClassName = "BequadroSchema";

    public const string HintName = ClassName + ".g.cs";

    public static string Emit(string fingerprint)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("/// <summary>");
        writer.Line("/// The schema set this project's FlatBuffers code was generated from.");
        writer.Line("/// </summary>");
        writer.OpenBlock($"public static class {ClassName}");
        writer.Line("/// <summary>");
        writer.Line(
            "/// A fingerprint of the schema set. Code generated from the same schemas, ignoring white space and"
        );
        writer.Line(
            "/// comments, has the same fingerprint in every language and on every platform. It may change between"
        );
        writer.Line("/// Bequadro versions.");
        writer.Line("/// </summary>");
        writer.Line($"public const string Fingerprint = \"{fingerprint}\";");
        writer.CloseBlock();
        return writer.ToString();
    }
}
