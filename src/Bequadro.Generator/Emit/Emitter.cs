using Bequadro.Generator.Common;
using Bequadro.Schema.Semantics;

namespace Bequadro.Generator.Emit;

/// <summary>
/// Produces the C# source for one declaration.
/// </summary>
internal static class Emitter
{
    public static string Emit(DeclarationModel model)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line("#pragma warning disable CS1591");
        writer.Line();
        if (model.Namespace.Length > 0)
        {
            writer.Line($"namespace {Naming.NamespaceName(model.Namespace)};");
            writer.Line();
        }

        writer.DocComment(model.Documentation, model.RenamedFrom);
        switch (model)
        {
            case EnumModel enumModel:
                EnumEmitter.Emit(writer, enumModel);
                break;
            case StructModel structModel:
                StructEmitter.Emit(writer, structModel);
                break;
            case TableModel tableModel:
                TableEmitter.Emit(writer, tableModel);
                break;
            case UnionModel unionModel:
                UnionEmitter.Emit(writer, unionModel);
                break;
            default:
                throw new InvalidOperationException($"Unknown declaration model {model.GetType().Name}.");
        }

        return writer.ToString();
    }
}
