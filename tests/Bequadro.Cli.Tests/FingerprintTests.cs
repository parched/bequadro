using System.Text.RegularExpressions;
using Bequadro.Schema;
using Bequadro.Schema.Syntax;

namespace Bequadro.Cli.Tests;

/// <summary>
/// SER-015, TS-002 and PY-002: the module that holds the schema set's fingerprint in each target.
/// </summary>
public sealed class FingerprintTests : IDisposable
{
    private const string A = "include \"b.fbs\";\nnamespace A;\n// A comment\ntable T { b: B.U; }\n";
    private const string B = "namespace B;\n/// Documented.\ntable U { x: int = 1; }\n";

    private readonly CliHarness _cli = new();

    public void Dispose() => _cli.Dispose();

    [Fact]
    public void Generate_TypeScript_WritesTheFingerprintModule()
    {
        WriteSchemas();

        _cli.GenerateTypeScript("schemas").Code.Should().Be(ExitCode.Success);

        _cli.Read("out/bequadro_schema.ts")
            .Should()
            .Be(
                $$"""
                // Code generated by Bequadro. DO NOT EDIT.

                /**
                 * A fingerprint of the schema set this code was generated from. Code generated from the same schemas,
                 * ignoring white space and comments, has the same fingerprint in every language and on every platform. It
                 * may change between Bequadro versions.
                 */
                export const fingerprint: string = "{{Expected()}}";

                """.ReplaceLineEndings("\n")
            );
    }

    [Fact]
    public void Generate_Python_WritesTheFingerprintModule()
    {
        WriteSchemas();

        GeneratePython("schemas").Code.Should().Be(ExitCode.Success);

        _cli.Read("out/bequadro_schema.py")
            .Should()
            .Be(
                $$""""
                # Code generated by Bequadro. DO NOT EDIT.
                """The schema set this package was generated from."""

                from typing import Final

                FINGERPRINT: Final[str] = "{{Expected()}}"
                """A fingerprint of the schema set this code was generated from.

                Code generated from the same schemas, ignoring white space and comments, has the same fingerprint in every
                language and on every platform. It may change between Bequadro versions.
                """

                """".ReplaceLineEndings("\n")
            );
    }

    /// <summary>
    /// The fingerprint doesn't depend on how the inputs name the files, their order, their line endings or the
    /// target.
    /// </summary>
    [Fact]
    public void Generate_SameTokensAnyInputs_GiveTheSameFingerprint()
    {
        WriteSchemas();
        _cli.Write("copy/b.fbs", B.Replace("\n", "\r\n"));
        _cli.Write("copy/a.fbs", "﻿" + A.Replace("// A comment", "/* Another */").Replace("\n", "\r\n"));

        var fingerprints = new[]
        {
            Generated("typescript", "schemas"),
            Generated("typescript", "schemas/b.fbs", "schemas/a.fbs"),
            Generated("typescript", Path.Combine(_cli.Directory, "schemas")),
            Generated("typescript", "copy"),
            Generated("python", "schemas"),
            Generated("python", "copy"),
        };

        fingerprints.Should().AllBe(Expected());
    }

    [Fact]
    public void Generate_ChangedToken_ChangesTheFingerprint()
    {
        WriteSchemas();
        var before = Generated("typescript", "schemas");

        _cli.Write("schemas/b.fbs", B.Replace("= 1", "= 2"));

        Generated("typescript", "schemas").Should().NotBe(before);
    }

    private void WriteSchemas()
    {
        _cli.Write("schemas/a.fbs", A);
        _cli.Write("schemas/b.fbs", B);
    }

    private static string Expected() =>
        SchemaFingerprint.Combine([Parser.Parse("/a.fbs", A).Digest, Parser.Parse("/b.fbs", B).Digest]);

    private (ExitCode Code, string Output, string Error) GeneratePython(params string[] inputs) =>
        _cli.Run(["generate", "--target", "python", "--out", "out", .. inputs]);

    private string Generated(string target, params string[] inputs)
    {
        _cli.Run(["generate", "--target", target, "--out", "out", .. inputs]).Code.Should().Be(ExitCode.Success);
        var module = _cli.Read(target == "python" ? "out/bequadro_schema.py" : "out/bequadro_schema.ts");
        return Regex.Match(module, "\"([0-9a-f]{32})\"").Groups[1].Value;
    }
}
