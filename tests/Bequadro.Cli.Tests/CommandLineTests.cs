namespace Bequadro.Cli.Tests;

/// <summary>
/// CLI-002 to CLI-004: arguments, usage errors, the schema set, diagnostics and exit codes.
/// </summary>
public sealed class CommandLineTests : IDisposable
{
    private readonly CliHarness _cli = new();

    public void Dispose() => _cli.Dispose();

    [Fact]
    public void Run_Version_PrintsThePackageVersion()
    {
        var result = _cli.Run("--version");

        result.Code.Should().Be(ExitCode.Success);
        // The version of the NuGet package: semantic, with a prerelease label for 0.0.0-unreleased or a prerelease tag, and
        // without the commit as build metadata
        result.Output.Trim().Should().MatchRegex(@"^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$");
    }

    [Theory]
    [InlineData("--help")]
    [InlineData("-h")]
    [InlineData("generate", "--help")]
    [InlineData("generate", "--help", "--target", "typescript")]
    [InlineData("generate", "--target", "rust", "-h", "--no-such-option")]
    public void Run_Help_PrintsUsage(params string[] args)
    {
        var result = _cli.Run(args);

        result.Code.Should().Be(ExitCode.Success);
        result.Output.Should().Contain("Usage: bequadro generate --target <typescript|python>");
    }

    [Theory]
    [InlineData("No command given.")]
    [InlineData("Unknown command 'build'.", "build")]
    [InlineData("Missing --target.", "generate", "--out", "out", "a.fbs")]
    [InlineData("Missing --out.", "generate", "--target", "typescript", "a.fbs")]
    [InlineData("No inputs given.", "generate", "--target", "typescript", "--out", "out")]
    [InlineData("Unknown target 'rust'", "generate", "--target", "rust", "--out", "out", "a.fbs")]
    [InlineData("Missing value for --out.", "generate", "--target", "typescript", "--out")]
    [InlineData("Missing value for --target.", "generate", "--target", "--out", "out", "a.fbs")]
    [InlineData("Unknown option '--verbose'.", "generate", "--verbose", "--target", "typescript", "--out", "o", "a")]
    [InlineData("Unknown import extension 'mjs'", "generate", "--import-extension", "mjs")]
    [InlineData(
        "--import-extension only applies to --target typescript.",
        "generate",
        "--target",
        "python",
        "--import-extension",
        "js",
        "--out",
        "out",
        "a.fbs"
    )]
    [InlineData(
        "--no-stubs only applies to --target python.",
        "generate",
        "--target",
        "typescript",
        "--no-stubs",
        "--out",
        "out",
        "a.fbs"
    )]
    [InlineData(
        "Input 'missing.fbs' does not exist.",
        "generate",
        "--target",
        "typescript",
        "--out",
        "out",
        "missing.fbs"
    )]
    [InlineData("Unexpected argument 'x' after --version.", "--version", "x")]
    [InlineData(
        "--out is given more than once.",
        "generate",
        "--out",
        "a",
        "--target",
        "python",
        "--out",
        "b",
        "a.fbs"
    )]
    [InlineData("--check is given more than once.", "generate", "--check", "--check")]
    [InlineData("Empty value for --target.", "generate", "--target", "", "--out", "out", "a.fbs")]
    [InlineData("Empty value for --import-extension.", "generate", "--import-extension", "")]
    public void Run_UsageError_ExitsWithTwoAndAMessage(string message, params string[] args)
    {
        var result = _cli.Run(args);

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().StartWith("bequadro: ").And.Contain(message);
        result.Output.Should().BeEmpty();
    }

    [Theory]
    [InlineData("Empty value for --out.", "--out", "", "a.fbs")]
    [InlineData("An input is empty.", "--out", "out", "")]
    [InlineData("An input is empty.", "--out", "out", "a.fbs", "")]
    public void Generate_EmptyOutOrInput_ExitsWithTwoAndWritesNothing(string message, params string[] args)
    {
        // As "$UNSET" gives: it must not mean the working directory
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.Write("old.ts", "// Code generated by Bequadro. DO NOT EDIT.\n");

        var result = _cli.Run(["generate", "--target", "typescript", .. args]);

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().Be($"bequadro: {message}\n".ReplaceLineEndings());
        _cli.Files(".").Should().Equal("a.fbs", "old.ts");
    }

    [Fact]
    public void Generate_SchemaErrors_PrintsSortedDiagnosticsWritesNothingAndExitsWithOne()
    {
        _cli.Write("schemas/b.fbs", "table B { x: Missing; }");
        _cli.Write("schemas/a.fbs", "table A {\n  y: Nope;\n  y: int;\n}");
        _cli.Write("out/keep.txt", "unrelated");

        var result = _cli.GenerateTypeScript("schemas");

        result.Code.Should().Be(ExitCode.Failure);
        var a = Path.Combine("schemas", "a.fbs");
        var b = Path.Combine("schemas", "b.fbs");
        result
            .Error.Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Should()
            .Equal(
                $"{a}:2:6: error BQ2003: Unknown type 'Nope'",
                $"{a}:3:3: error BQ2006: 'y' is already declared in 'A'",
                $"{b}:1:14: error BQ2003: Unknown type 'Missing'"
            );
        _cli.OutputFiles().Should().Equal("keep.txt");
    }

    [Fact]
    public void Generate_IncludeNotInInputs_ReportsIncludeNotFound()
    {
        _cli.Write("a.fbs", "include \"b.fbs\";\ntable A { b: B; }");
        _cli.Write("b.fbs", "table B {}");

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.Failure);
        result.Error.Should().Contain("a.fbs:1:1: error BQ2001:");
        _cli.GenerateTypeScript("a.fbs", "b.fbs").Code.Should().Be(ExitCode.Success);
    }

    [Fact]
    public void Generate_DirectoryAndFileInputs_UseEveryFbsFileOnce()
    {
        _cli.Write("schemas/a.fbs", "namespace A; table T {}");
        _cli.Write("schemas/nested/b.FBS", "namespace B; table T {}");
        _cli.Write("schemas/notes.txt", "not a schema");
        _cli.Write("extra.schema", "namespace C; table T {}");

        var result = _cli.GenerateTypeScript("schemas", "schemas/a.fbs", "extra.schema");

        result.Error.Should().BeEmpty();
        result.Code.Should().Be(ExitCode.Success);
        _cli.OutputFiles().Should().Equal("A.ts", "B.ts", "C.ts", "bequadro.ts", "bequadro_schema.ts");
    }

    [Fact]
    public void Generate_AbsoluteAndRelativeInputs_ResolveIncludesTheSameWay()
    {
        var a = _cli.Write("schemas/a.fbs", "include \"b.fbs\"; table A { b: B; }");
        _cli.Write("schemas/b.fbs", "table B {}");

        var result = _cli.GenerateTypeScript(a, "schemas/b.fbs");

        result.Error.Should().BeEmpty();
        result.Code.Should().Be(ExitCode.Success);
    }

    [Fact]
    public void Generate_InputOrder_DoesNotChangeTheOutput()
    {
        _cli.Write("a.fbs", "namespace N; table Foo { x: int; }");
        _cli.Write("b.fbs", "namespace N; table foo { y: int; } table Foo_ {}");

        _cli.GenerateTypeScript("a.fbs", "b.fbs");
        var first = _cli.Read("out/N.ts");
        _cli.GenerateTypeScript("b.fbs", "a.fbs");

        _cli.Read("out/N.ts").Should().Be(first);
    }

    [Fact]
    public void Generate_DirectoryWithoutSchemas_WritesOnlyTheRuntime()
    {
        _cli.Write("schemas/notes.txt", "not a schema");

        var result = _cli.GenerateTypeScript("schemas");

        result.Should().Be((ExitCode.Success, "", ""));
        _cli.OutputFiles().Should().Equal("bequadro.ts");
    }

    [Fact]
    public void Generate_FileReachedThroughASymbolicLink_IsCountedOnce()
    {
        _cli.Write("schemas/a.fbs", "namespace A; table T {}");
        _cli.Write("schemas/c.fbs", "include \"a.fbs\"; namespace C; table U { t: A.T; }");
        _cli.Link("link.fbs", Path.Combine("schemas", "a.fbs"), directory: false);
        _cli.Link("schemas/loop", ".", directory: true);

        var forwards = _cli.GenerateTypeScript("link.fbs", "schemas");
        var backwards = _cli.GenerateTypeScript("schemas", "link.fbs");

        forwards.Should().Be((ExitCode.Success, "", ""));
        backwards.Should().Be((ExitCode.Success, "", ""));
        _cli.OutputFiles().Should().Equal("A.ts", "C.ts", "bequadro.ts", "bequadro_schema.ts");
    }

    [Fact]
    public void Generate_DirectoryLinkedIntoAnInput_IsSearched()
    {
        _cli.Write("vendor/b.fbs", "namespace B; table U {}");
        _cli.Write("schemas/a.fbs", "include \"vendor/b.fbs\"; namespace A; table T { u: B.U; }");
        _cli.Link("schemas/vendor", Path.Combine("..", "vendor"), directory: true);

        var result = _cli.GenerateTypeScript("schemas");

        result.Should().Be((ExitCode.Success, "", ""));
        _cli.OutputFiles().Should().Equal("A.ts", "B.ts", "bequadro.ts", "bequadro_schema.ts");
    }

    [Fact]
    public void Generate_Diagnostics_ShowPathsAsTheInputsGaveThem()
    {
        _cli.Write("schemas/a.fbs", "namespace N;\ntable T {}");
        _cli.Write("schemas/b.fbs", "namespace N;\ntable T {}\ntable U { x: N.V; }");
        _cli.Write("schemas/c.fbs", "namespace N;\ntable V {}");
        _cli.Write("schemas/d.fbs", "include \"missing.fbs\";");

        var result = _cli.GenerateTypeScript("schemas");

        var a = Path.Combine("schemas", "a.fbs");
        var b = Path.Combine("schemas", "b.fbs");
        var c = Path.Combine("schemas", "c.fbs");
        var d = Path.Combine("schemas", "d.fbs");
        result
            .Error.Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Should()
            .Equal(
                $"{b}:2:7: error BQ2002: 'N.T' is already declared at {a}(2,7)",
                $"{b}:3:14: error BQ2004: Type 'N.V' is declared in '{c}', which is not included by this file",
                $"{d}:1:1: error BQ2001: Included file 'missing.fbs' (resolved to '{Path.Combine("schemas", "missing.fbs")}') is not in the schema set; add it to the inputs"
            );
    }

    [Fact]
    public void Generate_AbsoluteInput_ShowsAbsolutePathsInDiagnostics()
    {
        var a = _cli.Write("schemas/a.fbs", "include \"missing.fbs\";");

        var result = _cli.GenerateTypeScript(a);

        result.Error.Should().Contain($"(resolved to '{Path.Combine(_cli.Directory, "schemas", "missing.fbs")}')");
    }

    [Fact]
    public void Generate_Utf16Input_IsNotDecodedAsUtf16()
    {
        // CLI-003: files are UTF-8, whatever byte order mark they start with
        File.WriteAllText(Path.Combine(_cli.Directory, "a.fbs"), "table T {}", System.Text.Encoding.Unicode);
        File.WriteAllText(Path.Combine(_cli.Directory, "b.fbs"), "table U {}", System.Text.Encoding.UTF8);

        var utf16 = _cli.GenerateTypeScript("a.fbs");
        var utf8 = _cli.GenerateTypeScript("b.fbs");

        utf16.Code.Should().Be(ExitCode.Failure);
        utf16.Error.Should().Contain("a.fbs:1:1: error BQ1001");
        utf8.Should().Be((ExitCode.Success, "", ""));
    }

    [Fact]
    public void Generate_UnreadableInput_ExitsWithTwoAndSaysItCantBeRead()
    {
        CliHarness.SkipUnlessPermissionsApply();
        _cli.Write("schemas/a.fbs", "table T {}");
        _cli.Write("schemas/sub/b.fbs", "table U {}");
        using (_cli.Permissions("schemas/a.fbs", UnixFileMode.None))
        {
            _cli.GenerateTypeScript("schemas")
                .Should()
                .Be(
                    (
                        ExitCode.UsageOrIOError,
                        "",
                        $"bequadro: Can't read '{Path.Combine("schemas", "a.fbs")}': permission denied.\n"
                    )
                );
        }

        using (_cli.Permissions("schemas/sub", UnixFileMode.None))
        {
            _cli.GenerateTypeScript("schemas")
                .Should()
                .Be(
                    (
                        ExitCode.UsageOrIOError,
                        "",
                        $"bequadro: Can't read '{Path.Combine("schemas", "sub")}': permission denied.\n"
                    )
                );
        }

        _cli.OutputFiles().Should().BeEmpty();
    }
}
