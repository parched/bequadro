namespace Bequadro.Cli.Tests;

/// <summary>
/// CLI-005 and CLI-006: what is written to the output directory, and what is left alone.
/// </summary>
public sealed class OutputDirectoryTests : IDisposable
{
    private readonly CliHarness _cli = new();

    public void Dispose() => _cli.Dispose();

    [Fact]
    public void Generate_NewDirectory_WritesTheRuntimeAndOneModulePerNamespace()
    {
        _cli.Write("a.fbs", "table Root {} namespace A.B; table T {} namespace A; enum E : ubyte { X }");

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.Success);
        _cli.OutputFiles().Should().Equal("A.ts", "A/B.ts", "bequadro.ts", "bequadro_schema.ts", "index.ts");
        foreach (var file in _cli.OutputFiles())
        {
            // Read as bytes, because reading as text would strip a byte order mark
            var bytes = _cli.ReadBytes(Path.Combine("out", file));
            var text = new System.Text.UTF8Encoding(false, throwOnInvalidBytes: true).GetString(bytes);
            text.Should()
                .StartWith(
                    "// Code generated by Bequadro. DO NOT EDIT.\n",
                    "the file is UTF-8 with no byte order mark"
                );
            text.Should().EndWith("\n").And.NotContain("\r");
        }
    }

    [Fact]
    public void Generate_UnchangedFiles_KeepTheirModificationTimes()
    {
        _cli.Write("a.fbs", "namespace A; table T {} namespace B; table U {}");
        _cli.GenerateTypeScript("a.fbs");
        var old = new DateTime(2020, 1, 1, 0, 0, 0, DateTimeKind.Utc);
        File.SetLastWriteTimeUtc(Path.Combine(_cli.Output, "A.ts"), old);
        File.SetLastWriteTimeUtc(Path.Combine(_cli.Output, "B.ts"), old);

        _cli.Write("a.fbs", "namespace A; table T {} namespace B; table U { x: int; }");
        _cli.GenerateTypeScript("a.fbs").Code.Should().Be(ExitCode.Success);

        File.GetLastWriteTimeUtc(Path.Combine(_cli.Output, "A.ts")).Should().Be(old);
        File.GetLastWriteTimeUtc(Path.Combine(_cli.Output, "B.ts")).Should().NotBe(old);
    }

    [Fact]
    public void Generate_RemovedNamespace_DeletesItsModuleAndEmptyDirectoriesButNothingElse()
    {
        _cli.Write("a.fbs", "namespace A.B.C; table T {} namespace D; table U {}");
        _cli.GenerateTypeScript("a.fbs");
        _cli.Write("out/notes.md", "hand-written");
        _cli.Write("out/D/keep.ts", "export const x = 1;\n");

        _cli.Write("a.fbs", "namespace E; table T {}");
        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.Success);
        _cli.OutputFiles().Should().Equal("D/keep.ts", "E.ts", "bequadro.ts", "bequadro_schema.ts", "notes.md");
        Directory.Exists(Path.Combine(_cli.Output, "A")).Should().BeFalse();
    }

    [Fact]
    public void Generate_PathTakenByAFileThatIsNotGenerated_WritesNothingAndExitsWithTwo()
    {
        _cli.Write("a.fbs", "namespace A; table T {} namespace B; table U {}");
        _cli.Write("out/A.ts", "// mine\n");

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().Contain("'A.ts' in the output directory exists and wasn't generated by Bequadro");
        _cli.OutputFiles().Should().Equal("A.ts");
        _cli.Read("out/A.ts").Should().Be("// mine\n");
    }

    [Fact]
    public void Generate_Check_ListsChangesWithoutWritingAndExitsWithOneUntilUpToDate()
    {
        _cli.Write("a.fbs", "namespace A; table T {} namespace B; table U {}");
        _cli.GenerateTypeScript("a.fbs");
        _cli.Write("a.fbs", "namespace A; table T { x: int; } namespace C; table V {}");

        var check = _cli.GenerateTypeScript("--check", "a.fbs");

        check.Code.Should().Be(ExitCode.Failure);
        check
            .Output.Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Should()
            .Equal("would update A.ts", "would create C.ts", "would update bequadro_schema.ts", "would delete B.ts");
        _cli.OutputFiles().Should().Equal("A.ts", "B.ts", "bequadro.ts", "bequadro_schema.ts");

        _cli.GenerateTypeScript("a.fbs");
        var upToDate = _cli.GenerateTypeScript("--check", "a.fbs");
        upToDate.Code.Should().Be(ExitCode.Success);
        upToDate.Output.Should().BeEmpty();
    }

    [Fact]
    public void Generate_Runtime_IsTheEmbeddedRuntime()
    {
        _cli.Write("a.fbs", "table T {}");

        _cli.GenerateTypeScript("a.fbs");

        var runtime = _cli.Read("out/bequadro.ts");
        runtime.Should().StartWith("// Code generated by Bequadro. DO NOT EDIT.\n");
        runtime.Should().Contain("export class FlatBufferDataError extends Error");
    }

    [Fact]
    public void Generate_Files_AreUtf8WithoutAByteOrderMark()
    {
        _cli.Write("a.fbs", "namespace A;\n/// Ünïcödé\ntable T {}");

        _cli.GenerateTypeScript("a.fbs").Code.Should().Be(ExitCode.Success);

        var bytes = _cli.ReadBytes("out/A.ts");
        bytes.AsSpan(0, 3).ToArray().Should().Equal("// "u8.ToArray());
        System.Text.Encoding.UTF8.GetString(bytes).Should().Contain("Ünïcödé");
    }

    [Fact]
    public void Generate_ChangedFile_IsReplacedNotRewrittenInPlace()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.GenerateTypeScript("a.fbs");
        var old = _cli.Read("out/A.ts");
        using var reader = new FileStream(
            Path.Combine(_cli.Output, "A.ts"),
            FileMode.Open,
            FileAccess.Read,
            FileShare.ReadWrite | FileShare.Delete
        );

        _cli.Write("a.fbs", "namespace A; table T { x: int; }");
        _cli.GenerateTypeScript("a.fbs").Code.Should().Be(ExitCode.Success);

        // A reader that opened the old file still reads all of it: the new content went to another file, which was
        // renamed over it (CLI-005)
        using var text = new StreamReader(reader);
        text.ReadToEnd().Should().Be(old);
        _cli.Read("out/A.ts").Should().NotBe(old).And.Contain("x");
        _cli.OutputFiles().Should().Equal("A.ts", "bequadro.ts", "bequadro_schema.ts");
    }

    [Fact]
    public void Generate_WorkingDirectory_DoesNotChangeTheOutput()
    {
        _cli.Write("schemas/a.fbs", "include \"b.fbs\"; namespace A; table T { b: B.U; }");
        _cli.Write("schemas/b.fbs", "namespace B; table U {}");
        _cli.Write("elsewhere/keep.txt", "");

        _cli.GenerateTypeScript("schemas").Code.Should().Be(ExitCode.Success);
        var first = _cli.OutputFiles().ToDictionary(f => f, f => _cli.ReadBytes(Path.Combine("out", f)));
        Directory.Delete(_cli.Output, recursive: true);
        var result = CliHarness.RunIn(
            Path.Combine(_cli.Directory, "elsewhere"),
            "generate",
            "--target",
            "typescript",
            "--out",
            Path.Combine("..", "out"),
            Path.Combine(_cli.Directory, "schemas", "b.fbs"),
            Path.Combine("..", "schemas", "a.fbs")
        );

        result.Error.Should().BeEmpty();
        _cli.OutputFiles().Should().Equal(first.Keys.Order(StringComparer.Ordinal));
        foreach (var (file, bytes) in first)
        {
            _cli.ReadBytes(Path.Combine("out", file)).Should().Equal(bytes);
        }
    }

    [Fact]
    public void Generate_SymbolicLinkToAnotherDirectory_IsNotFollowed()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.Write("other/gen/theirs.ts", "// Code generated by Bequadro. DO NOT EDIT.\nexport const theirs = 1;\n");
        _cli.Write("other/gen/hand.ts", "hand\n");
        _cli.Link("out/vendor", Path.Combine("..", "other", "gen"), directory: true);
        _cli.Link("out/theirs.ts", Path.Combine("..", "other", "gen", "theirs.ts"), directory: false);

        var check = _cli.GenerateTypeScript("--check", "a.fbs");
        var result = _cli.GenerateTypeScript("a.fbs");

        check.Output.Should().NotContain("delete");
        result.Error.Should().BeEmpty();
        result.Code.Should().Be(ExitCode.Success);
        _cli.Files("other/gen").Should().Equal("hand.ts", "theirs.ts");
        _cli.OutputFiles().Should().Equal("A.ts", "bequadro.ts", "bequadro_schema.ts", "theirs.ts", "vendor");
    }

    [Fact]
    public void Generate_PlannedDirectoryIsASymbolicLink_WritesNothingAndExitsWithTwo()
    {
        _cli.Write("a.fbs", "namespace A; table T {} namespace B.C; table U {}");
        Directory.CreateDirectory(Path.Combine(_cli.Directory, "other"));
        _cli.Link("out/B", Path.Combine("..", "other"), directory: true);

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().Contain($"'B' in the output directory is a symbolic link");
        _cli.Files("other").Should().BeEmpty();
        _cli.OutputFiles().Should().Equal("B");
    }

    [Fact]
    public void Generate_PlannedFileIsASymbolicLink_WritesNothingAndExitsWithTwo()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        var target = _cli.Write("other/A.ts", "// Code generated by Bequadro. DO NOT EDIT.\n");
        _cli.Link("out/A.ts", Path.Combine("..", "other", "A.ts"), directory: false);

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().Contain("'A.ts' in the output directory is a symbolic link");
        File.ReadAllText(target).Should().Be("// Code generated by Bequadro. DO NOT EDIT.\n");
        _cli.OutputFiles().Should().Equal("A.ts");
    }

    [Fact]
    public void Generate_FileWhereADirectoryIsPlanned_WritesNothingAndExitsWithTwo()
    {
        _cli.Write("a.fbs", "namespace foo.bar; table T {}");
        _cli.Write("out/foo", "mine\n");

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result
            .Error.Should()
            .Be(
                "bequadro: 'foo' in the output directory is a file, where a directory would be generated; nothing was written.\n".ReplaceLineEndings()
            );
        _cli.OutputFiles().Should().Equal("foo");
    }

    [Fact]
    public void Generate_OutputDirectoryIsAFile_ExitsWithTwo()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.Write("outfile", "mine\n");

        var result = _cli.Run("generate", "--target", "typescript", "--out", "outfile", "a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().Be("bequadro: The output directory 'outfile' is a file.\n".ReplaceLineEndings());
        _cli.Read("outfile").Should().Be("mine\n");
    }

    [Fact]
    public void Generate_FileThatOnlyStartsLikeTheGeneratedComment_IsNotGenerated()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.Write("out/notes.txt", "// Code generated by Bequadro. DO NOT EDIT. (not really)\nmine\n");
        _cli.Write("out/A.ts", "// Code generated by Bequadro. DO NOT EDIT.!\n");

        var check = _cli.GenerateTypeScript("--check", "a.fbs");
        var result = _cli.GenerateTypeScript("a.fbs");

        check.Output.Should().NotContain("notes.txt");
        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().Contain("'A.ts' in the output directory exists and wasn't generated by Bequadro");
        _cli.OutputFiles().Should().Equal("A.ts", "notes.txt");
    }

    [Fact]
    public void Generate_GeneratedFileWithWindowsLineEndings_IsStillGenerated()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.Write("out/A.ts", "// Code generated by Bequadro. DO NOT EDIT.\r\nold\r\n");
        _cli.Write("out/B.ts", "# Code generated by Bequadro. DO NOT EDIT.\r\n");

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Error.Should().BeEmpty();
        _cli.OutputFiles().Should().Equal("A.ts", "bequadro.ts", "bequadro_schema.ts");
    }

    [Fact]
    public void Generate_HiddenFiles_AreNeverDeleted()
    {
        // Such as another run's temporary file, which starts with the generated comment
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.Write("out/.A.ts.0123456789abcdef0123456789abcdef.tmp", "// Code generated by Bequadro. DO NOT EDIT.\n");
        _cli.Write("out/.hidden/B.ts", "// Code generated by Bequadro. DO NOT EDIT.\n");

        _cli.GenerateTypeScript("a.fbs").Code.Should().Be(ExitCode.Success);

        _cli.OutputFiles()
            .Should()
            .Equal(
                ".A.ts.0123456789abcdef0123456789abcdef.tmp",
                ".hidden/B.ts",
                "A.ts",
                "bequadro.ts",
                "bequadro_schema.ts"
            );
    }

    [Fact]
    public void Generate_UnreadableGeneratedFile_ExitsWithTwoAndSaysItCantBeRead()
    {
        CliHarness.SkipUnlessPermissionsApply();
        _cli.Write("a.fbs", "namespace A; table T {}");
        _cli.GenerateTypeScript("a.fbs");
        _cli.Write("a.fbs", "namespace A; table T { x: int; }");
        using var _ = _cli.Permissions("out/A.ts", UnixFileMode.None);

        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result
            .Error.Should()
            .Be($"bequadro: Can't read '{Path.Combine("out", "A.ts")}': permission denied.\n".ReplaceLineEndings());
    }

    [Fact]
    public void Generate_UnwritableOutputDirectory_ExitsWithTwoAndSaysItCantBeWritten()
    {
        CliHarness.SkipUnlessPermissionsApply();
        _cli.Write("a.fbs", "namespace A; table T {}");
