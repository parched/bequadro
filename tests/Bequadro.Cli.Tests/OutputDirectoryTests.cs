    [Fact]
    public void Generate_CheckForPython_ListsChangesWithoutWriting()
    {
        _cli.Write("a.fbs", "namespace A; table T {}");
        string[] python = ["generate", "--target", "python", "--out", "out"];
        _cli.Run([.. python, "a.fbs"]).Code.Should().Be(ExitCode.Success);
        _cli.Write("a.fbs", "namespace B; table T {}");

        var check = _cli.Run([.. python, "--check", "a.fbs"]);

        check.Code.Should().Be(ExitCode.Failure);
        check
            .Output.Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Should()
            .Equal(
                $"would create {Path.Combine("B", "__init__.py")}",
                "would update bequadro_schema.py",
                $"would delete {Path.Combine("A", "__init__.py")}"
            );
        _cli.OutputFiles().Should().Equal("A/__init__.py", "__init__.py", "bequadro.py", "bequadro_schema.py");
        _cli.Run([.. python, "a.fbs"]).Code.Should().Be(ExitCode.Success);
        _cli.Run([.. python, "--check", "a.fbs"]).Should().Be((ExitCode.Success, "", ""));
    }

    [Fact]
    public void Generate_ConcurrentRunsOnOneDirectory_NeverMistakeGeneratedFilesForOthers()
    {
        // Two schema sets with the same namespaces, generated alternately into one directory, as a dev server and a
        // test runner might, while a third run checks it
        var namespaces = Enumerable.Range(0, 40).Select(i => $"namespace N{i}; table T {{}}");
        _cli.Write("one.fbs", string.Join('\n', namespaces));
        _cli.Write("two.fbs", string.Join('\n', namespaces.Select(n => n.Replace("{}", "{ x: int; }"))));
        var errors = new System.Collections.Concurrent.ConcurrentBag<string>();

        void Loop(params string[] args)
        {
            for (var i = 0; i < 30; i++)
            {
                var result = _cli.GenerateTypeScript(args);
                if (result.Code == ExitCode.UsageOrIOError)
                {
                    errors.Add(result.Error);
                }
            }
        }

        Parallel.Invoke(() => Loop("one.fbs"), () => Loop("two.fbs"), () => Loop("--check", "one.fbs"));

        errors.Should().BeEmpty();
    }
