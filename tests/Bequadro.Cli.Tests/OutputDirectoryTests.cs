        var result = _cli.GenerateTypeScript("a.fbs");

        result.Code.Should().Be(ExitCode.UsageOrIOError);
        result.Error.Should().MatchRegex(@"^bequadro: Can't write 'out[/\\][^']+': permission denied\.\r?\n$");
    }

